<?php

final class PostgresColumnMapper
{
    // Traduit la description d’une colonne en définition SQL PostgreSQL.
    public static function definition(array $column): string
    {
        $name = $column['COLUMN_NAME'];
        DatabaseCopySnapshot::identifier($name);

        if (strlen($name) > 63) {
            throw new HttpError('Nom de colonne trop long pour PostgreSQL.', 422);
        }

        if (in_array(strtolower($name), ['tableoid', 'xmin', 'cmin', 'xmax', 'cmax', 'ctid'], true)) {
            throw new HttpError("Nom de colonne réservé par PostgreSQL : $name.", 422);
        }

        $mysqlType = strtolower($column['COLUMN_TYPE']);
        $extra = strtolower(trim($column['EXTRA']));
        $identity = $extra === 'auto_increment';

        if ($column['GENERATION_EXPRESSION'] !== '') {
            throw new HttpError('Les colonnes calculées ne sont pas prises en charge.', 422);
        }

        if ($extra !== '' && !$identity) {
            throw new HttpError("Attribut non pris en charge pour $name.", 422);
        }

        if ($column['COLUMN_DEFAULT'] !== null) {
            throw new HttpError("Valeur par défaut non prise en charge pour $name.", 422);
        }

        $type = match ($mysqlType) {
            'int' => 'INTEGER',
            'int unsigned' => 'BIGINT',
            'text' => 'TEXT',
            'date' => 'DATE',
            default => self::parameterizedType($mysqlType),
        };

        if ($identity && !in_array($type, ['INTEGER', 'BIGINT'], true)) {
            throw new HttpError('Identifiant automatique non pris en charge.', 422);
        }

        $definition = '"' . $name . '" ' . $type;

        if ($identity) {
            $definition .= ' GENERATED BY DEFAULT AS IDENTITY';
            if ($mysqlType === 'int unsigned') $definition .= ' (MAXVALUE 4294967295)';
        }

        if ($column['IS_NULLABLE'] === 'NO') {
            $definition .= ' NOT NULL';
        }

        if ($mysqlType === 'int unsigned') {
            $definition .= ' CHECK ("' . $name . '" BETWEEN 0 AND 4294967295)';
        }

        return $definition;
    }

    // Conserve la longueur des textes et la précision des décimaux.
    private static function parameterizedType(string $type): string
    {
        if (preg_match('/^varchar\(([1-9][0-9]*)\)$/D', $type, $matches)) {
            return 'VARCHAR(' . $matches[1] . ')';
        }

        if (preg_match('/^decimal\(([1-9][0-9]*),([0-9]+)\)$/D', $type, $matches)) {
            return 'NUMERIC(' . $matches[1] . ',' . $matches[2] . ')';
        }

        throw new HttpError("Type MySQL non pris en charge : $type.", 422);
    }
}